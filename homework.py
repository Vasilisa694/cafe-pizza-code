menu = {
    "Пицца пеперони": 500,
    "картофель фри": 200,
    "кола": 100,
    "сырные палочки": 300,
    "пицца маргарита": 450,
    "пицца BBQ": 550,
    "паста болоньезе": 375,
    "комбо 3 в 1": 750
}

cart = []

print("--- Меню пиццерии ---\n"
 "Пицца пеперони — 500 руб.\n"
 "картофель фри — 200 руб.\n"
 "кола — 100 руб.\n"
 "сырные палочки - 300 руб.\n"
 "пицца маргарита - 450 руб.\n"
 "пицца BBQ - 550 руб.\n"
 "паста болоньезе - 375 руб.\n"
 "комбо 3 в 1  (пицца пеперони + кола + картофель фри) - 750 руб.")

while True:
    choice = input("\nЧто хотите заказать? ( введите названия или 'стоп' для оплаты): ")

    if choice == "стоп":
        break

    if choice in menu:
        cart.append(choice)
        print(f"{choice} добавлен(а) в корзину!")
    else:
        print("Такого блюда нет.")

total = 0
for item in cart:
    total = total + menu[item]

print(f"\nВаш заказ: {cart}")
print(f"Сумма к оплате: {total} руб.")
print("спасибо за ваш заказ!")





